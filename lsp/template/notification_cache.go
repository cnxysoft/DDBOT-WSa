// notificationPic 是通知函数表 pic 的缓存实现，签名与命令侧 pic 一致
// （input interface{}, args ...interface{}），参数经 parsePicArgs 归一化。
//
// 证据（成品 notificationPic @0xb5a4a0，notification_cache.go:341）：
//  1. 先判定入参是否 http(s) 字符串（+0x3d 比较 "http://"、+0xa0 比较
//     "https://"）：非字符串/非 URL 直接落 pic @0xb3cb00（funcs_ext.go:681）；
//  2. URL 入参经 parsePicArgs @0xb3b260（funcs_ext.go:554）拆出 alt/params，
//     仅 params[0] 走 getTemplateFetchMode @0xb3ac00（funcs_ext.go:494）；
//     取值为 "remote"（+0x1ab 比较 "remote"）时同样直接落 pic；
//  3. 否则合并参数并强制 DDBOT_REQ_FETCH="local"（+0x2aa mapassign
//     "DDBOT_REQ_FETCH" @0x10ae720），键 = notificationRequestKey(scope,
//     "IMAGE" @0x109abae, url, merged...)（+0x332）；
//  4. requestKey 返回 false 时退到 picUriWithParams @0xb3a380（funcs_ext.go:410）
//     再套 .Alternative(alt)（+0x7c1）；
//  5. do 的闭包 notificationPic.func1 @0xb5aea0 深拷贝参数表后调 preProcess
//     （funcs_request_ext.go:71，@0xb4ac40）与 utils.ImageGet（utils/image.go:41），
//     命中/失败返回的缓存体由主函数用 mmsg.NewImage(...).Alternative(alt) 组装；
//  6. 失败日志 "template: cached notification image error %v" @0x10d8043，
//     并返回空 Buf + Alternative(alt) 的元素。
func notificationPic(scope string, input interface{}, args ...interface{}) (e *mmsg.ImageBytesElement) {
	uri, isString := input.(string)
	if !isString || !(strings.HasPrefix(uri, "http://") || strings.HasPrefix(uri, "https://")) {
		return pic(input, args...)
	}
	alt, params := parsePicArgs(args)
	if len(params) > 0 && getTemplateFetchMode(params[0]) == "remote" {
		return pic(input, args...)
	}

	merged := mergePicParams(params...)
	if len(merged) == 0 {
		merged = []map[string]interface{}{{}}
	}
	merged[0][DDBOT_REQ_FETCH] = "local"

	key, ok := notificationRequestKey(scope, "IMAGE", uri, merged...)
	if !ok {
		return picUriWithParams(uri, merged...).Alternative(alt)
	}
	resp, err := notificationCacheInstance().do(key, func() (notificationCachedResponse, error) {
		copied := make([]map[string]interface{}, len(merged))
		for i, p := range merged {
			if p == nil {
				continue
			}
			m := make(map[string]interface{}, len(p))
			for k, v := range p {
				m[k] = v
			}
			copied[i] = m
		}
		_, opts := preProcess(copied)
		fetched, err := localutils.ImageGet(uri, opts...)
		return notificationCachedResponse{body: fetched}, err
	})
	if err != nil {
		logger.Errorf("template: cached notification image error %v", err)
		return mmsg.NewImage(nil, uri).Alternative(alt)
	}
	return mmsg.NewImage(resp.body, uri).Alternative(alt)
}
