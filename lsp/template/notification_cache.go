//go:noinline
func notificationTemplateFuncs(scope string) FuncMap {
	return FuncMap{
		"httpGet": func(url string, oParams ...map[string]interface{}) []byte {
			return notificationHTTPGet(scope, url, oParams...)
		},
		"httpHead": func(url string, oParams ...map[string]interface{}) requests.RespHeader {
			return notificationHTTPHead(scope, url, oParams...)
		},
		"httpPostJson": func(url string, oParams ...map[string]interface{}) []byte {
			return notificationHTTPBody(scope, "POST_JSON", url, oParams, executeHTTPPostJSON)
		},
		"httpPostForm": func(url string, oParams ...map[string]interface{}) []byte {
			return notificationHTTPBody(scope, "POST_FORM", url, oParams, executeHTTPPostForm)
		},
		"parseBiliPost": func(Url string) []PostElement {
			return notificationGetBiliPost(scope, Url)
		},
		"pic": func(input interface{}, args ...interface{}) *mmsg.ImageBytesElement {
			return notificationPic(scope, input, args...)
		},
	}
}

// notificationHTTPGet 缓存版 httpGet，返回响应体。
//
// 证据（成品 notificationHTTPGet @0xb58ae0，notification_cache.go:264）：
//   - 键 = notificationRequestKey(scope, "GET" @0x1098824, url, oParams...)；
//   - requestKey 失败时退到非缓存 httpGet @0xb4cf40(url, oParams...)（没有日志）；
//   - do 的闭包 func1 @0xb58de0 先深拷贝参数表（makeslice @0x48ef60 + per-map
//     makemap），再调 executeHTTPGet @0xb4cda0（funcs_request_ext.go:230），
