// sync.Once 单例在语义上等价，只是多一个符号。
func notificationCacheInstance() *notificationCache {
	notificationCacheOnce.Do(func() {
		notificationCacheSharedInst = newNotificationCache()
	})
	return notificationCacheSharedInst
}

// notificationTemplateScope 判定模板是否走通知缓存函数表，并生成该通知的
// 缓存 scope 串（缓存键的第一段）。
//
// 证据（成品 notificationTemplateScope @0xb578a0，notification_cache.go:154）：
//   - 先对 data 做 map[string]interface{} 类型断言（类型槽 0xf65ce0），失败
//     返回 ("", false)；
//   - 模板名做两次 31 字节 memequal，只命中 @0x10c5547 的
//     "notify.group.bilibili.live.tmpl" 与 @0x10c55c3 的
//     "notify.group.bilibili.news.tmpl"；
//   - live 分支：data["uid"]（@0x1098821，3 字节）与 data["live_time"]
//     （@0x10a600b，9 字节）走 mapaccess2，任一不存在即返回 ("", false)；
//     scope = fmt.Sprintf("%s|uid=%v|live_time=%v|living=%v|title=%v|title_changed=%v",
//     name, uid, live_time, living, title, title_changed)（格式串 @0x10e3c7c，
//     58 字节；living/title/title_changed 走 mapaccess1，缺失即零值）；
//   - news 分支：data["dynamic"]（@0x10a3128，7 字节）走 mapaccess2，缺失返回
//     ("", false)；scope = name + "|" + 值，值 = notificationStringValue(dynamic,
//     "Id"@0x109827c、"id"@0x1098263)，为空再取
//     notificationStringValue(dynamic, "DynamicUrl"@0x10a7ce1、
//     "dynamic_url"@0x10a91f2)，两次都空则返回 ("", false)。
func notificationTemplateScope(name string, data interface{}) (string, bool) {
	m, ok := data.(map[string]interface{})
	if !ok {
		return "", false
	}
	switch name {
	case "notify.group.bilibili.live.tmpl":
		uid, ok := m["uid"]
		if !ok {
			return "", false
		}
		liveTime, ok := m["live_time"]
		if !ok {
			return "", false
		}
		living := m["living"]
		title := m["title"]
		titleChanged := m["title_changed"]
		return fmt.Sprintf("%s|uid=%v|live_time=%v|living=%v|title=%v|title_changed=%v",
			name, uid, liveTime, living, title, titleChanged), true
	case "notify.group.bilibili.news.tmpl":
		dynamic, ok := m["dynamic"]
		if !ok {
			return "", false
		}
		s := notificationStringValue(dynamic, "Id", "id")
		if s == "" {
			s = notificationStringValue(dynamic, "DynamicUrl", "dynamic_url")
		}
		if s == "" {
			return "", false
		}
		return name + "|" + s, true
	}
	return "", false
}

// notificationStringValue 按 keys 依次从 v 里取出字符串值。
//
// 证据（成品 notificationStringValue @0xb57cc0，notification_cache.go:187，
// 832 字节）：
//   - 入口 (v interface{}, keys ...string)：AX/BX 是接口 type/data，
//     CX/DI/SI 是 keys ptr/len/cap；type==nil 时直接返回 ""；
//   - 先走 reflect.Value.Elem（@0x4c29a0）循环解 Ptr/Interface，并内联
//     reflect.Value.IsNil（nil 即返回 ""，panic 串 "reflect.Value.IsNil"
//     @0x10b35e0）；
//   - 之后只分派 Map(21) 与 Struct(25) 两支（cmp $0x15/$0x19），
//     其余 Kind（含 String=24）一律返回 ""——成品没有 String 直取分支；
//   - Map：逐个 key 走 reflect.Value.MapIndex（@0x4b2960），命中即
//     reflect.valueInterface（@0x4ceee0）+ fmt.Sprint（@0x51ee40）；未命中取下一个
//     key；
//   - Struct：逐个 key 走 reflect.Value.FieldByName（@0x4c31a0）；invalid 或带 RO
//     位（flag&0x60，即未导出字段）的跳过，否则 valueInterface + fmt.Sprint；
//   - 全部未命中返回 ""。
func notificationStringValue(v interface{}, keys ...string) string {
	rv := reflect.ValueOf(v)
	for rv.IsValid() && (rv.Kind() == reflect.Ptr || rv.Kind() == reflect.Interface) {
		if rv.IsNil() {
			return ""
		}
		rv = rv.Elem()
	}
	if !rv.IsValid() {
		return ""
	}
	switch rv.Kind() {
	case reflect.Map:
		for _, k := range keys {
			mv := rv.MapIndex(reflect.ValueOf(k))
			if mv.IsValid() {
				return fmt.Sprint(mv.Interface())
			}
		}
	case reflect.Struct:
		for _, k := range keys {
			f := rv.FieldByName(k)
			if f.IsValid() && f.CanInterface() {
				return fmt.Sprint(f.Interface())
			}
		}
	}
	return ""
}

// notificationRequestKey 根据 scope、请求名、URL 与参数表生成缓存键。
//
// 证据（成品 notificationRequestKey @0xb58820，notification_cache.go:241，
// 704 字节，返回 (string, bool)）：
//   - 参数是 variadic []map[string]interface{}：入口 R9/R10/R11 是 slice 头，
//     经 runtime.convTslice @0x489d20 装箱后交给 encoding/json.Marshal
//     @0x5460c0；Marshal 的 error 类型槽非 0 时返回 ("", false)（@0xb58a53）；
//   - 键输入 = sha256(scope + "\x00" + name + "\x00" + part + "\x00" + json)：
//     runtime.concatbytes @0x471b20 拼接 6 个串 [scope, sep, name, sep, part, sep]
//     （sep 是 @0x1124090 的 1 字节串，内容 0x00），再用 growslice @0x48f040 +
//     memmove @0x494aa0 把 json 字节 append 到末尾，最后 crypto/sha256.Sum256
//     @0x695520；
//   - 返回 fmt.Sprintf("%x", sum[:])（fmt.Sprintf @0x51eb00，格式串 "%x"
//     @0x109838a）+ true（CL=1）。
func notificationRequestKey(scope string, name string, part string, params ...map[string]interface{}) (string, bool) {
	data, err := json.Marshal(params)
	if err != nil {
		return "", false
	}
	sum := sha256.Sum256(append([]byte(scope+"\x00"+name+"\x00"+part+"\x00"), data...))
	return fmt.Sprintf("%x", sum[:]), true
}

