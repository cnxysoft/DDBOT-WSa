// notificationCacheDefaultTTL 是通知模板 HTTP 缓存的固定有效期：5 分钟。
//
// 证据（DDBOT-Lite x64，(*notificationCache).store @0xb56e80）：
// store 没有 ttl 参数，直接在 time.Time.Add 前硬编码时长：
//
//	b5765b: movabs $0x45d964b800,%rdi   ; 0x45d964b800 = 300e9 ns = 300s
//	b57665: call   time.Time.Add
//
// 即 expiresAt = now.Add(5 * time.Minute)。
const notificationCacheDefaultTTL = 5 * time.Minute

// notificationCacheMaxBytes 是通知缓存所有条目 size() 之和的上限：64 MiB。
//
// 证据（DDBOT-Lite x64，(*notificationCache).store @0xb56e80）：
// 函数开头对单条 response 的 size() 求和后 cmp $0x4000000,%rcx; jg ret
// （单条超过 64MiB 直接不缓存），淘汰判断处又有
// cmp $0x4000000,%rsi; jle <insert>（总量+新条目超过 64MiB 才开始淘汰）。
const notificationCacheMaxBytes = 64 * 1024 * 1024

// notificationCacheMaxEntries 是通知缓存的条目数上限：达到该数量即开始淘汰。
//
// 证据：成品淘汰前 cmp $0x7f,%rsi; jg <evict>（map count > 127 即淘汰），
// 即插入后最多保留 128 条。
const notificationCacheMaxEntries = 128

// notificationCachedResponse 是一条缓存的 HTTP 响应：响应体与响应头。
type notificationCachedResponse struct {
	body    []byte
	headers requests.RespHeader
}

// size 返回本条缓存占用的字节数，用于容量统计。
//
// 证据：成品里存在一对符号 notificationCachedResponse.size
// （notification_cache.go:38，值接收者，64 字节）与
// (*notificationCachedResponse).size（<autogenerated>，224 字节），
// 说明源码用的是值接收者；函数体把 body 与 RespHeader 全部 7 个字段的
// 长度相加：值方法 @0xb55fe0 读取接收者的 0x10/0x28/0x38/0x48/0x58/0x68/
// 0x78/0x88 八个 len 并累加（body.len + Server/Date/ContentDisposition/
// ContentLength/ContentEncoding/ContentType/Connection 的 len）。
//
// 两个符号在默认构建下都保活的机制见 (*notificationCache).do 的注释：
// 装箱成 interface{} 会保留 notificationCachedResponse 的 rtype
// （0xfdf9a0，Size_=0x88），其 uncommonType 方法表条目
// （0xfdfa40: Name=0xd97, Mtyp=0xc800, Ifn=0x75eb00, Tfn=0x754fe0）
// 分别以 textOff 引用指针包装器（+0x401000=0xb5fb00）与值方法
// （+0x401000=0xb55fe0）。
func (r notificationCachedResponse) size() int {
	return len(r.body) +
		len(r.headers.Server) +
		len(r.headers.Date) +
		len(r.headers.ContentDisposition) +
		len(r.headers.ContentLength) +
		len(r.headers.ContentEncoding) +
		len(r.headers.ContentType) +
		len(r.headers.Connection)
}

// notificationCacheEntry 是通知缓存中的一条记录。
//
// 字段布局对齐成品（map value 192 字节 = 0xC0）：
//
//	response  0x00..0x87（notificationCachedResponse 值，136 字节）
//	created   0x88、expires 0xA0、size 0xB8
//
// 字段名与类型取自 recovered/types/types-closure-x64.tsv:9537
// （struct 192 template.notificationCacheEntry struct { response
// template.notificationCachedResponse; created time.Time; expires time.Time; size int }）。
// 证据：get @0xb569a0 从 map value 偏移 0xA0 读 time.Time 做
// now.After(expires)，从 0xB8 读 int 做总量扣减；store @0xb56e80
// 淘汰循环从 0x88 读 created 做 Before 比较。
type notificationCacheEntry struct {
	response notificationCachedResponse
	created  time.Time
	expires  time.Time
	size     int
}

// notificationCache 是通知模板专用的进程内缓存。
// 与命令侧模板不同，通知在同一周期内可能被多个群复用同一份资源。
//
// 字段布局：mu 0x00、entries 0x08、size 0x10、sf 0x18。
// 证据：(*notificationCache).do @0xb56020 在调用 singleflight 前执行
// add $0x18,%rax，把 c+0x18 作为 *singleflight.Group 接收者传入。
type notificationCache struct {
	mu      sync.Mutex
	entries map[string]notificationCacheEntry
	size    int // 所有条目的 size() 之和，对应成品 c+0x10
	sf      singleflight.Group
}

func newNotificationCache() *notificationCache {
	return &notificationCache{
		entries: make(map[string]notificationCacheEntry),
	}
}

// do 先查缓存，未命中时用 golang.org/x/sync/singleflight 合并同一 key 的并发拉取。
//
// 证据（DDBOT-Lite x64，(*notificationCache).do @0xb56020，源行 notification_cache.go:64）：
//   - 调用图：+0xa5 -> (*notificationCache).get；+0x172 ->
//     golang.org/x/sync/singleflight.(*Group).Do（singleflight.go:91）；
//     +0x2c0 -> runtime.growslice、+0x2f3 -> runtime.memmove（深拷贝 body）；
//     +0x458 -> runtime.panicdottypeE（v.(notificationCachedResponse) 断言失败时 panic）。
//   - 入口只保存 RAX/RBX/RCX/RDI 四个参数寄存器 = c/key.ptr/key.len/fetch，
//     没有 ttl 参数。
//   - 返回值是「notificationCachedResponse 值 + error」：结果值写在
//     0x200(%rsp)（调用方结果区），error 走 RAX/RBX。
//   - 传给 singleflight 的闭包 do.func1 @0xb564e0（源行 :69）先用
//     get 复查缓存，未命中才调 fetch，拿到值后 store 再深拷贝一份装箱；
//     装箱用 runtime.convT（rtype 0xfdf9a0），do 再用
//     v.(notificationCachedResponse) 取回。
//
// 默认（内联）构建下两个 size 符号都保活，靠的正是 do.func1 里的这次
// interface{} 装箱：值类型 notificationCachedResponse 的 rtype 被保留，
// 其方法表以 textOff 同时引用值方法 0xb55fe0 与指针包装器 0xb5fb00。
func (c *notificationCache) do(key string, fetch func() (notificationCachedResponse, error)) (notificationCachedResponse, error) {
	if resp, ok := c.get(key); ok {
		return resp, nil
	}
	v, err, _ := c.sf.Do(key, func() (interface{}, error) {
		if resp, ok := c.get(key); ok {
			return resp, nil
		}
		resp, err := fetch()
		if err != nil {
			return nil, err
		}
		c.store(key, resp)
		cloned := resp
		cloned.body = append([]byte(nil), resp.body...)
		return cloned, nil
	})
	if err != nil {
		return notificationCachedResponse{}, err
	}
	resp := v.(notificationCachedResponse)
	cloned := resp
	cloned.body = append([]byte(nil), resp.body...)
	return cloned, nil
}

// get 读取一条缓存；命中且未过期时返回深拷贝。
//
// 证据：成品 (*notificationCache).get @0xb569a0（源行 notification_cache.go:86，
// defer 在 :88）返回「notificationCachedResponse 值 + bool」：结果值写到
// 0x1f8(%rsp)（get 帧顶之上的调用方结果区），bool 走 AL
// （b56ce2: movzbl 0x36(%rsp),%eax）。命中时先 growslice+memmove
// 深拷贝 body 再返回，避免调用方改动污染缓存。
func (c *notificationCache) get(key string) (notificationCachedResponse, bool) {
	c.mu.Lock()
	defer c.mu.Unlock()
	entry, ok := c.entries[key]
	if !ok {
		return notificationCachedResponse{}, false
	}
	if time.Now().After(entry.expires) {
		delete(c.entries, key)
		return notificationCachedResponse{}, false
	}
	cloned := entry.response
	cloned.body = append([]byte(nil), entry.response.body...)
	return cloned, true
}

// store 写入一条缓存，并清理过期与超容量的旧记录。
//
// 签名与容量策略对齐成品 (*notificationCache).store @0xb56e80（2528 字节，
// 源行 notification_cache.go:101，defer 在 :108）：
//  0. 没有 ttl 参数；响应以「值」而非指针传入（136 字节的
//     notificationCachedResponse 从 0x2c8(%rsp) 的调用方栈参数区读入，
//     寄存器只放 receiver(RAX) 与 key(RBX/RCX)）。
//     expiresAt 固定为 now.Add(5 * time.Minute)（b5765b movabs $0x45d964b800）。
//  1. 先按 size() 为该条 response 计费，超过 notificationCacheMaxBytes 的单条直接放弃
//     （b56f64: cmp $0x4000000,%rcx; jg ret）；
//  2. 加锁、time.Now()，先遍历 map 删除 now.After(expires) 的过期条目并按
//     entry.size 扣减总量（b570d8 time.Time.After / b57120 mapdelete / b5712d 扣减）；
//  3. 再按「条目数 >= notificationCacheMaxEntries(128)」或「总量+新条目 > 64MiB」
//     循环淘汰：每轮挑 created 最早的一条删除（b57392 time.Time.Before 递增选最小），
//     删除后回到判断处复检（b571f1 扣减后直接落回 b57209 的判断）；
//  4. 命中已存在的 key 时先扣掉旧条目 size（b57432 mapaccess2 / b574cc 扣减），
//     再深拷贝 body（b57588 growslice + b575b2 memmove）后覆盖写入；
//  5. 最后 mapassign 写 entry 并 c.size += size（b57764 / b577e7）。
func (c *notificationCache) store(key string, resp notificationCachedResponse) {
	size := resp.size()
	if size > notificationCacheMaxBytes {
		// 单条就超过总容量上限：存进去只会把整个缓存清空，直接放弃。
		return
	}
	c.mu.Lock()
	defer c.mu.Unlock()
	// now 与成品一致，在持锁后取样，供过期判断与 created/expires 共用。
	now := time.Now()
	// 1) 先清掉所有已过期条目。
	for k, e := range c.entries {
		if now.After(e.expires) {
			delete(c.entries, k)
			c.size -= e.size
		}
	}
	// 2) 按条目数与总字节数双重上限淘汰，每轮淘汰 created 最早的一条。
	for len(c.entries) >= notificationCacheMaxEntries || c.size+size > notificationCacheMaxBytes {
		var (
			victimKey  string
			victimTime time.Time
			hasVictim  bool
		)
		for k, e := range c.entries {
			if !hasVictim || e.created.Before(victimTime) {
				victimKey, victimTime, hasVictim = k, e.created, true
			}
		}
		if !hasVictim {
			break
		}
		c.size -= c.entries[victimKey].size
		delete(c.entries, victimKey)
	}
	// 3) 覆盖同一 key 时先退掉旧条目占用的容量。
	if old, ok := c.entries[key]; ok {
		c.size -= old.size
	}
	// 4) 深拷贝响应体，避免调用方之后修改底层数组污染缓存。
	c.entries[key] = notificationCacheEntry{
		response: notificationCachedResponse{
			body:    append([]byte(nil), resp.body...),
			headers: resp.headers,
		},
		created: now,
		expires: now.Add(notificationCacheDefaultTTL),
		size:    size,
	}
	c.size += size
}

