// notificationCacheInstance 返回通知模板共用的缓存实例（懒初始化单例）。
// 通知渲染与命令渲染共享进程，但通知缓存独立于命令侧的直接请求。
//
// 证据：成品 HTTPGet/HTTPHead/HTTPBody/GetBiliPost/Pic 的 do 调用点都直接从
// 全局槽 0x1b90880 取 *notificationCache（如 notificationHTTPGet @0xb58be8:
